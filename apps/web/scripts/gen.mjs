#!/usr/bin/env node
/**
 * Code generation for the web app's API contracts.
 *
 *   node scripts/gen.mjs [openapi|schemas|all] [--check]
 *
 * openapi  apps/api/openapi.json (or openapi.placeholder.json until the API PR lands)
 *          → src/api/generated/openapi.ts                       (openapi-typescript)
 * schemas  packages/schemas/jsonschema/*.schema.json
 *          → src/api/generated/schemas/<name>.ts + index.ts     (json-schema-to-typescript)
 *
 * --check  generate in memory and exit 1 if any committed file differs (CI staleness gate).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import openapiTS, { astToString } from 'openapi-typescript';
import prettier from 'prettier';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = resolve(WEB, '../..');
const OUT = join(WEB, 'src/api/generated');
const OPENAPI_REAL = join(REPO, 'apps/api/openapi.json');
const OPENAPI_PLACEHOLDER = join(WEB, 'openapi.placeholder.json');
const SCHEMA_DIR = join(REPO, 'packages/schemas/jsonschema');

const args = process.argv.slice(2);
const check = args.includes('--check');
const target = args.find((a) => !a.startsWith('--')) ?? 'all';

const BANNER = (src) =>
  `/* eslint-disable */\n// AUTO-GENERATED by apps/web/scripts/gen.mjs from ${src}. Do not edit; run \`pnpm gen\`.\n\n`;

async function format(code) {
  return prettier.format(code, { parser: 'typescript', singleQuote: true, printWidth: 100 });
}

async function genOpenapi() {
  const src = existsSync(OPENAPI_REAL) ? OPENAPI_REAL : OPENAPI_PLACEHOLDER;
  const spec = JSON.parse(readFileSync(src, 'utf8'));
  const ast = await openapiTS(spec, { alphabetize: true });
  const rel = relative(REPO, src);
  return { [join(OUT, 'openapi.ts')]: await format(BANNER(rel) + astToString(ast)) };
}

/** packages/schemas/jsonschema/shot_timeline.schema.json → ShotTimeline / shot-timeline.ts */
function names(file) {
  const stem = basename(file, '.schema.json');
  const pascal = stem.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());
  return { stem, kebab: stem.replace(/_/g, '-'), pascal };
}

async function genSchemas() {
  const files = readdirSync(SCHEMA_DIR)
    .filter((f) => f.endsWith('.schema.json'))
    .sort();
  const out = {};
  const index = [];
  for (const f of files) {
    const schema = JSON.parse(readFileSync(join(SCHEMA_DIR, f), 'utf8'));
    const { kebab, pascal } = names(f);
    // Root-level unions (ws_server_event) have no title; give them a stable one.
    schema.title ??= pascal;
    const ts = await compile(schema, pascal, {
      bannerComment: '',
      additionalProperties: false,
      unreachableDefinitions: true,
      strictIndexSignatures: true,
      style: { singleQuote: true, printWidth: 100 },
    });
    out[join(OUT, 'schemas', `${kebab}.ts`)] = await format(
      BANNER(`packages/schemas/jsonschema/${f}`) + ts,
    );
    index.push(`export type * as ${pascal}Schema from './${kebab}';`);
  }
  // Several schemas share $defs (ShotType, Shot…); json-schema-to-typescript emits identical
  // declarations in each file, so the barrel namespaces each file to avoid duplicate-name clashes.
  out[join(OUT, 'schemas', 'index.ts')] = await format(
    BANNER('packages/schemas/jsonschema/*.schema.json') + index.join('\n') + '\n',
  );
  return out;
}

const generated = {
  ...(target === 'all' || target === 'openapi' ? await genOpenapi() : {}),
  ...(target === 'all' || target === 'schemas' ? await genSchemas() : {}),
};

let stale = 0;
for (const [path, content] of Object.entries(generated)) {
  const rel = relative(WEB, path);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== content) {
      stale++;
      console.error(`✗ stale: ${rel}`);
    }
  } else if (current !== content) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`✓ wrote ${rel}`);
  } else {
    console.log(`· unchanged ${rel}`);
  }
}

if (check) {
  if (stale > 0) {
    console.error(
      `\n${stale} generated file(s) are stale. Run \`pnpm -C apps/web gen\` and commit.`,
    );
    process.exit(1);
  }
  console.log(`✓ ${Object.keys(generated).length} generated file(s) up to date`);
}
